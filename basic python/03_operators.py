# Arithmetic, comparison and logical operators

a = 15
b = 4

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor division:", a // b)
print("Modulus:", a % b)
print("Power:", a ** b)

print("a > b:", a > b)
print("a == b:", a == b)
print("a > 10 and b > 10:", a > 10 and b > 10)
print("a > 10 or b > 10:", a > 10 or b > 10)
